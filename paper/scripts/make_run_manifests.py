#!/usr/bin/env python3
"""Generate paper/facts/runs/R-00{1..5}.md from the ingested 2026-10-17 cache-campaign JSONL.
Commands are copied from Plans/cache-optimisation-logbook.md §3 (R-004/R-005 had none recorded).
Re-running must reproduce the files byte-for-byte (checked in the 2026-10-18 session)."""
import json, hashlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
D = ROOT / 'facts/data/2026-10-17-cache-campaign'
runs = [
 ('R-001','cache_campaign1_k4.jsonl','cache_campaign1_k4_text.jsonl','./.build/release/diffusion-bench llada --arms q-cached,q-uncached,cache-clean-commit,cache-pool,cache-fp8,cache-k8v4,cache-fp4,cache-fp8-clean,cache-k8v4-clean,cache-csa2-periodic-k4 --suites chat,reasoning,code --runs 1 --gen-length 64 --warmup-once --json scratch/cache_campaign1_k4.jsonl --text-out scratch/cache_campaign1_k4_text.jsonl'),
 ('R-002','cache_campaign1b_k4.jsonl',None,'./.build/release/diffusion-bench llada --arms q-cached,cache-k8v4,cache-fp4,cache-fp8-clean,cache-k8v4-clean,cache-csa2-periodic-k4 --suites chat,reasoning,code --runs 1 --gen-length 64 --warmup-once --json scratch/cache_campaign1b_k4.jsonl'),
 ('R-003','cache_campaign2_k1.jsonl','cache_campaign2_k1_text.jsonl','./.build/release/diffusion-bench llada --arms spk-1,cache-clean-commit-k1,cache-csa2-legacy,cache-csa2-periodic,cache-flashblock-tau4,cache-flashblock-int2,cache-dual-opt,cache-dual-k8v4 --speculation-k 1 --suites chat,reasoning,code --runs 1 --gen-length 64 --warmup-once --json scratch/cache_campaign2_k1.jsonl --text-out scratch/cache_campaign2_k1_text.jsonl'),
 ('R-004','cache_k8v4_clean_k1.jsonl',None,'UNRECORDED — no command in the logbook; arm cache-k8v4-clean-k1 per row fields'),
 ('R-005','track1_kv_starvation_k1.jsonl','track1_kv_starvation_k1_text.jsonl','UNRECORDED in logbook §8 — 8 arms at K=1 per row fields (see arm order below)'),
]
for rid, f, t, cmd in runs:
    rows = [json.loads(l) for l in (D / f).open()]
    tc = rows[0].get('toolchain', {})
    order = []
    for r in rows:
        if not order or order[-1] != r['arm']:
            order.append(r['arm'])
    blocked = len(order) == len(set(order))
    warm = [r for r in rows if r.get('warmupIncluded') or r.get('run', 0) < 0]
    inv = [(r['arm'], r['promptId'], round(r['env']['freeMemoryMBBefore']), round(r['env']['swapUsedMBAfter'] - r['env']['swapUsedMBBefore']))
           for r in rows if not r.get('envValid') and not (r.get('warmupIncluded') or r.get('run', 0) < 0)]
    sha = lambda p: hashlib.sha256((D / p).read_bytes()).hexdigest()
    lines = [f"id: {rid}", f"command: {cmd}",
             "git: UNRECORDED (rows predate the gitCommit field; the tree was uncommitted — HEAD at the time was at or before 1ff0053)",
             f"host: {sorted(set(r['host'] for r in rows))} (16 GB)",
             f"toolchain: mlxSwiftPackage={tc.get('mlxSwiftPackage')} mlxCoreVersion={tc.get('mlxCoreVersion')} swiftCompiler={tc.get('swiftCompiler')}",
             "model artefact: models/llada2-1-mini-4bit (sha256 of weights not recorded)",
             f"data: [{f}](../data/2026-10-17-cache-campaign/{f}) sha256={sha(f)}"]
    if t:
        lines.append(f"text data: [{t}](../data/2026-10-17-cache-campaign/{t}) sha256={sha(t)}")
    lines += [f"processId: {sorted(set(r.get('processId') for r in rows))}",
              f"genLength: {sorted(set(r.get('genLength') for r in rows))}, speculationK: {sorted(set(r.get('speculationK') for r in rows))}",
              f"rows: total={len(rows)} warmup={len(warm)} envValid=false (non-warmup)={len(inv)}",
              f"arm order: {'blocked (sequential, one process)' if blocked else 'interleaved'}: {' -> '.join(order)}",
              "envValid=false rows (arm, prompt, freeMB_before, swap_delta_MB):"]
    lines += [f"  - {a}, {p}, {fm}, {sd}" for a, p, fm, sd in inv] or ["  - none"]
    lines.append("generated by: paper/scripts/make_run_manifests.py (2026-10-18)")
    out = ROOT / f'facts/runs/{rid}.md'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
